package io.tenantkit.provisioning;

import java.sql.Timestamp;
import java.time.Duration;
import java.time.Instant;

import javax.sql.DataSource;

import io.tenantkit.core.TenantId;
import org.h2.jdbcx.JdbcDataSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

/**
 * H2 (fast tier) fixture for provisioning tests: in-memory database,
 * {@code DataSourceTransactionManager} + {@code TransactionTemplate}, the
 * in-process lock stand-in, and the application-side ledger migration
 * (per ADR-0001 the kit never creates the table itself &mdash; in real apps
 * Flyway/Liquibase does).
 */
final class H2ProvisioningFixture {

    final JdbcTemplate jdbc;
    final SeedScriptLocator locator;
    final SeedLedger ledger;
    final InProcessLockManager lockManager;
    final DefaultTenantProvisioner provisioner;

    private H2ProvisioningFixture(JdbcTemplate jdbc, SeedScriptLocator locator, SeedLedger ledger,
            InProcessLockManager lockManager, DefaultTenantProvisioner provisioner) {
        this.jdbc = jdbc;
        this.locator = locator;
        this.ledger = ledger;
        this.lockManager = lockManager;
        this.provisioner = provisioner;
    }

    /** Adds the ledger table to an already-built fixture (application-side duty). */
    H2ProvisioningFixture migrated() {
        jdbc.execute(H2_LEDGER_DDL);
        return this;
    }

    /** H2-native shape of the ledger table (the reference DDL is MySQL-flavored). */
    private static final String H2_LEDGER_DDL = """
            CREATE TABLE IF NOT EXISTS tenantkit_seed_history (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              tenant_id VARCHAR(32) NOT NULL,
              script_name VARCHAR(255) NOT NULL,
              checksum VARCHAR(64) NOT NULL,
              executed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
              CONSTRAINT uk_tenantkit_seed UNIQUE (tenant_id, script_name)
            )""";

    /** Fresh in-memory DB with the ledger table migrated (application-side duty). */
    static H2ProvisioningFixture withMigratedLedger() {
        H2ProvisioningFixture fixture = new H2ProvisioningFixture.Builder().build();
        fixture.jdbc.execute(H2_LEDGER_DDL);
        return fixture;
    }

    /** Fresh in-memory DB without the ledger table (startup WARN / TK-2004 scenarios). */
    static H2ProvisioningFixture withoutLedgerTable() {
        return new H2ProvisioningFixture.Builder().build();
    }

    static final class Builder {

        private String seedLocation = "classpath:db/tenant-seed/";
        private String ledgerTable = "tenantkit_seed_history";
        private boolean defaultDryRun = false;
        private Duration defaultLockTimeout = Duration.ofSeconds(30);
        private SeedLedger customLedger;

        Builder seedLocation(String location) {
            this.seedLocation = location;
            return this;
        }

        Builder ledgerTable(String table) {
            this.ledgerTable = table;
            return this;
        }

        Builder defaultDryRun(boolean dryRun) {
            this.defaultDryRun = dryRun;
            return this;
        }

        Builder defaultLockTimeout(Duration timeout) {
            this.defaultLockTimeout = timeout;
            return this;
        }

        Builder ledger(SeedLedger ledger) {
            this.customLedger = ledger;
            return this;
        }

        H2ProvisioningFixture build() {
            JdbcDataSource dataSource = new JdbcDataSource();
            dataSource.setURL("jdbc:h2:mem:provisioning-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1");
            JdbcTemplate jdbc = new JdbcTemplate(dataSource);
            SeedScriptLocator locator = new SeedScriptLocator(seedLocation);
            SeedLedger ledger = customLedger != null ? customLedger : new SeedLedger(jdbc, ledgerTable);
            InProcessLockManager lockManager = new InProcessLockManager();
            DefaultTenantProvisioner provisioner = new DefaultTenantProvisioner(locator, ledger, lockManager,
                    new TransactionTemplate(new DataSourceTransactionManager(dataSource)), jdbc,
                    defaultLockTimeout, defaultDryRun);
            return new H2ProvisioningFixture(jdbc, locator, ledger, lockManager, provisioner);
        }
    }

    /** Records one ledger row the way the application would inspect it. */
    int ledgerRowCount(String tenantId) {
        Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM tenantkit_seed_history WHERE tenant_id = ?",
                Integer.class, tenantId);
        return count == null ? 0 : count;
    }

    /** Convenience for tests simulating a concurrent recorder. */
    void insertLedgerRow(TenantId tenant, String scriptName, String checksum) {
        jdbc.update("INSERT INTO tenantkit_seed_history (tenant_id, script_name, checksum, executed_at) "
                + "VALUES (?, ?, ?, ?)", tenant.value(), scriptName, checksum, Timestamp.from(Instant.now()));
    }
}

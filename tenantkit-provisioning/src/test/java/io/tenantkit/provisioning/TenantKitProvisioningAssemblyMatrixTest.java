package io.tenantkit.provisioning;

import javax.sql.DataSource;

import io.tenantkit.test.HidingClassLoader;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.boot.autoconfigure.AutoConfigurations;
import org.springframework.boot.test.context.runner.ApplicationContextRunner;
import org.springframework.boot.test.system.CapturedOutput;
import org.springframework.boot.test.system.OutputCaptureExtension;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.SimpleDriverDataSource;
import org.springframework.transaction.PlatformTransactionManager;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Provisioning assembly matrix (DESIGN &sect;5 speed table, guard
 * {@code @ConditionalOnClass(JdbcTemplate)} + {@code tenantkit.provisioning.enabled}):
 * default assembly and property binding, module switch, absent spring-jdbc,
 * absent JdbcTemplate bean, user-provided provisioner and lock manager
 * overrides, missing-ledger startup WARN.
 */
@ExtendWith(OutputCaptureExtension.class)
class TenantKitProvisioningAssemblyMatrixTest {

    private final ApplicationContextRunner runner = new ApplicationContextRunner()
            .withConfiguration(AutoConfigurations.of(TenantKitProvisioningAutoConfiguration.class))
            .withUserConfiguration(JdbcUserConfig.class);

    private static final String H2_LEDGER_DDL = """
            CREATE TABLE IF NOT EXISTS tenantkit_seed_history (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              tenant_id VARCHAR(32) NOT NULL, script_name VARCHAR(255) NOT NULL,
              checksum VARCHAR(64) NOT NULL, executed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
              CONSTRAINT uk_tenantkit_seed UNIQUE (tenant_id, script_name))""";

    /** P01 - default assembly: provisioner + ledger + locator, property defaults bound. */
    @Test
    void p01_defaultAssemblyRegistersProvisionerWithDefaults() {
        runner.run(context -> {
            assertThat(context).hasNotFailed();
            assertThat(context).hasSingleBean(TenantProvisioner.class);
            assertThat(context.getBean(TenantProvisioner.class)).isInstanceOf(DefaultTenantProvisioner.class);
            assertThat(context).hasSingleBean(SeedLedger.class);
            assertThat(context).hasSingleBean(SeedScriptLocator.class);
            var properties = context.getBean(io.tenantkit.provisioning.properties.TenantKitProvisioningProperties.class);
            assertThat(properties.isEnabled()).isTrue();
            assertThat(properties.getSeedLocation()).isEqualTo("classpath:db/tenant-seed/");
            assertThat(properties.getLedgerTable()).isEqualTo("tenantkit_seed_history");
            assertThat(properties.getLockTimeoutSeconds()).isEqualTo(30);
            assertThat(properties.isDryRun()).isFalse();
        });
    }

    /** P02 - module switch off: no kit provisioning beans, user beans unaffected. */
    @Test
    void p02_moduleSwitchDisablesEverything() {
        runner.withPropertyValues("tenantkit.provisioning.enabled=false").run(context -> {
            assertThat(context).hasNotFailed();
            assertThat(context).doesNotHaveBean(TenantProvisioner.class);
            assertThat(context).doesNotHaveBean(SeedLedger.class);
            assertThat(context).doesNotHaveBean(SeedScriptLocator.class);
            assertThat(context).hasBean("sharedJdbcTemplate");
        });
    }

    /** P03 - spring-jdbc absent (hidden classloader): auto-configuration silently backs off. */
    @Test
    void p03_missingSpringJdbcBacksOff() {
        new ApplicationContextRunner()
                .withConfiguration(AutoConfigurations.of(TenantKitProvisioningAutoConfiguration.class))
                .withPropertyValues("tenantkit.provisioning.enabled=true")
                .withClassLoader(new HidingClassLoader(getClass().getClassLoader(), "org.springframework.jdbc"))
                .run(context -> {
                    assertThat(context).hasNotFailed();
                    assertThat(context).doesNotHaveBean(TenantProvisioner.class);
                    assertThat(context).doesNotHaveBean(SeedLedger.class);
                });
    }

    /** P04 - JdbcTemplate bean absent: guards back off, context starts. */
    @Test
    void p04_missingJdbcTemplateBeanAssemblesNothing() {
        new ApplicationContextRunner()
                .withConfiguration(AutoConfigurations.of(TenantKitProvisioningAutoConfiguration.class))
                .run(context -> {
                    assertThat(context).hasNotFailed();
                    assertThat(context).doesNotHaveBean(TenantProvisioner.class);
                    assertThat(context).doesNotHaveBean(SeedLedger.class);
                    assertThat(context).doesNotHaveBean(SeedScriptLocator.class);
                });
    }

    /** P05 - dry-run / lock timeout / ledger table / seed location bind into properties. */
    @Test
    void p05_propertiesBind() {
        runner.withPropertyValues("tenantkit.provisioning.dry-run=true",
                "tenantkit.provisioning.lock-timeout-seconds=42",
                "tenantkit.provisioning.ledger-table=custom_seed_history",
                "tenantkit.provisioning.seed-location=file:/opt/tenant-seeds/").run(context -> {
            assertThat(context).hasNotFailed();
            var properties = context.getBean(io.tenantkit.provisioning.properties.TenantKitProvisioningProperties.class);
            assertThat(properties.isDryRun()).isTrue();
            assertThat(properties.getLockTimeoutSeconds()).isEqualTo(42);
            assertThat(properties.getLedgerTable()).isEqualTo("custom_seed_history");
            assertThat(properties.getSeedLocation()).isEqualTo("file:/opt/tenant-seeds/");
            assertThat(context.getBean(SeedScriptLocator.class)).isNotNull();
        });
    }

    /** P06 - a user-provided TenantProvisioner wins over the kit default. */
    @Test
    void p06_userProvisionerBeanWins() {
        runner.withUserConfiguration(CustomProvisionerConfig.class).run(context -> {
            assertThat(context).hasNotFailed();
            assertThat(context.getBean(TenantProvisioner.class)).isInstanceOf(RecordingProvisioner.class);
            assertThat(context).hasSingleBean(SeedLedger.class);
        });
    }

    /** P07 - a user-provided TenantLockManager replaces the MySQL GET_LOCK default. */
    @Test
    void p07_userLockManagerReplacesMysqlDefault() {
        runner.withUserConfiguration(CustomLockConfig.class).run(context -> {
            assertThat(context).hasNotFailed();
            assertThat(context).hasSingleBean(TenantLockManager.class);
            assertThat(context.getBeansOfType(MysqlGetLockManager.class))
                    .as("the default lock manager is wired inline, never as a bean").isEmpty();
            assertThat(context).hasSingleBean(TenantProvisioner.class);
        });
    }

    /** P08 - ledger table missing: startup WARN with guidance, context still starts. */
    @Test
    void p08_missingLedgerTableWarnsAtStartup(CapturedOutput output) {
        new ApplicationContextRunner()
                .withConfiguration(AutoConfigurations.of(TenantKitProvisioningAutoConfiguration.class))
                .withUserConfiguration(JdbcWithoutLedgerConfig.class)
                .run(context -> {
                    assertThat(context).hasNotFailed();
                    assertThat(output.getAll()).contains("tenantkit_seed_history").contains("CREATE TABLE");
                });
    }

    @Configuration(proxyBeanMethods = false)
    static class JdbcUserConfig {

        @Bean
        DataSource sharedDataSource() {
            SimpleDriverDataSource dataSource = new SimpleDriverDataSource();
            dataSource.setDriver(new org.h2.Driver());
            dataSource.setUrl("jdbc:h2:mem:provisioning-matrix-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1");
            return dataSource;
        }

        @Bean
        JdbcTemplate sharedJdbcTemplate(DataSource dataSource) {
            JdbcTemplate jdbcTemplate = new JdbcTemplate(dataSource);
            jdbcTemplate.execute(H2_LEDGER_DDL);
            return jdbcTemplate;
        }

        @Bean
        PlatformTransactionManager sharedTransactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }
    }

    /** Same JDBC stack but no ledger migration - isolates the startup WARN. */
    @Configuration(proxyBeanMethods = false)
    static class JdbcWithoutLedgerConfig {

        @Bean
        DataSource bareDataSource() {
            SimpleDriverDataSource dataSource = new SimpleDriverDataSource();
            dataSource.setDriver(new org.h2.Driver());
            dataSource.setUrl("jdbc:h2:mem:provisioning-matrix-bare-" + System.nanoTime() + ";DB_CLOSE_DELAY=-1");
            return dataSource;
        }

        @Bean
        JdbcTemplate bareJdbcTemplate(DataSource dataSource) {
            return new JdbcTemplate(dataSource);
        }

        @Bean
        PlatformTransactionManager bareTransactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }
    }

    @Configuration(proxyBeanMethods = false)
    static class CustomProvisionerConfig {

        @Bean
        TenantProvisioner myOwnProvisioner() {
            return new RecordingProvisioner();
        }
    }

    static final class RecordingProvisioner implements TenantProvisioner {

        @Override
        public ProvisionReport provision(io.tenantkit.core.TenantId id, SeedProfile profile,
                ProvisionOptions options) {
            return new ProvisionReport(id, java.util.List.of(), java.util.List.of(), java.util.List.of(), false);
        }

        @Override
        public ProvisionReport repair(io.tenantkit.core.TenantId id, SeedProfile profile) {
            return new ProvisionReport(id, java.util.List.of(), java.util.List.of(), java.util.List.of(), false);
        }
    }

    @Configuration(proxyBeanMethods = false)
    static class CustomLockConfig {

        @Bean
        TenantLockManager myOwnLockManager() {
            return new InProcessLockManager();
        }
    }
}
